"""Generate LaTeX tables for the report from saved results CSVs.

Numbers in the report come only from files the notebooks wrote, never typed by
hand. Run from the repository root:

    python reports/latex/make_tables.py
"""

import ast
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
RESULTS_DIR = ROOT / "reports" / "results"
TABLES_DIR = ROOT / "reports" / "latex" / "tables"

MODEL_NAMES = {"OLS": "OLS", "Ridge": "Ridge", "ElasticNet": "Elastic Net"}
PARAM_NAMES = {"alpha": r"$\alpha$", "l1_ratio": r"$\rho_{L1}$"}


def format_params(params_text):
    params = ast.literal_eval(params_text)
    if not params:
        return "--"
    return ", ".join(f"{PARAM_NAMES.get(k, k)}={v}" for k, v in params.items())


def format_number(value):
    return "--" if pd.isna(value) else f"{value:.2f}"


def linear_baseline_table():
    results = pd.read_csv(RESULTS_DIR / "linear_baseline_results.csv")
    rows = [
        " & ".join([
            MODEL_NAMES.get(row.model, row.model),
            format_params(row.params),
            format_number(row.val_mae),
            format_number(row.val_rmse),
            format_number(row.test_mae),
            format_number(row.test_rmse),
        ]) + r" \\"
        for row in results.itertuples()
    ]
    return "\n".join([
        "% Generated by reports/latex/make_tables.py from",
        "% reports/results/linear_baseline_results.csv. Do not edit by hand.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Linear baseline on raw settings and sensors (FD001). Validation: 100 cut-off points "
        r"from 20 held-out engines. Test: 100 engines, scored once for the model chosen on validation. "
        r"Units: cycles.}",
        r"\label{tab:linear_baseline}",
        r"\resizebox{\columnwidth}{!}{%",
        r"\begin{tabular}{llcccc}",
        r"\toprule",
        r"Model & Hyperparameters & Val MAE & Val RMSE & Test MAE & Test RMSE \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}}",
        r"\end{table}",
        "",
    ])


if __name__ == "__main__":
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    out = TABLES_DIR / "linear_baseline.tex"
    out.write_text(linear_baseline_table())
    print("wrote", out.relative_to(ROOT))
